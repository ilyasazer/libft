#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	char			*str;
	unsigned int	size;
	unsigned int	i;

	if (s == NULL || f == NULL)
		return (NULL);
	size = ft_strlen(s) + 1;
	i = 0;
	str = malloc(sizeof(char) * size);
	if (str == NULL)
		return (NULL);
	while (s[i])
	{
		str[i] = f(i, s[i]);
		i++;
	}
	str[i] = '\0';
	return (str);
}
